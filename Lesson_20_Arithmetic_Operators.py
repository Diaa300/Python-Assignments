# ------------------------------
# -- Arithmetic Operators --
# ------------------------------
# [+] Addition
# [-] Subtraction
# [*] Multiplication
# [/] Division
# [%] Modulus
# [**] Exponent
# [//] Floor Division
# ------------------------------

# Addition

print (1 + 2) # 3
print (-10 + 18) # 8
print (2 + 3.27) # 5.27
print (1.2 + 1.2) # 2.4

# Subtraction

print (51 - 14.62) # 36.38
print (20 - 2.65) # 17.35
print (-50 - -40) # -10
print (60 - 30) # 30

# Multiplication

print (49 * 6) # 294
print (65 * 3 + 8) # 203
print ((10 + 3) * 100) # 1300
print (10 * 8 - 30) # 50

# Division

print (100 / 20) # 5.0
print (int(100 / 20)) # 5

# Modulus

print (8 % 2)  # 0
print (13 % 2) # 1
print (220 % 5) # 0
print (22 % 5) # 2

# Exponent

print (2 ** 5) # 32
print (2 * 2 * 2 * 2 * 2) # 32
print (5 ** 4) # 625 

# Floor Division

print(100 // 20) # 5
print(119 // 20) # 5
print(120 // 20) # 6
print(140 // 20) # 7 
print(140 // 20) # 7

